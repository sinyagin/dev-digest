import type { CiPostAs, CiTrigger } from '@devdigest/shared';
import {
  ACTION_CHECKOUT,
  ACTION_SETUP_NODE,
  ACTION_UPLOAD_ARTIFACT,
  ARTIFACT_FILE,
  ARTIFACT_NAME,
  GITHUB_TOKEN_SECRET,
  NODE_VERSION,
  OPENROUTER_SECRET,
  RUNNER_ENTRY,
  TRIGGER_ORDER,
} from './constants.js';

/**
 * The GitHub Actions workflow generator (SPEC-04 D11/D14/D15).
 *
 * SECURITY: the only variable inputs are a closed-set trigger list, a closed-set
 * post mode and the agent slug — and the slug is re-validated against
 * `[a-z0-9-]{1,64}` right here, so no agent- or user-authored text can reach the
 * file. The `run:` body is a constant (`RUN_COMMAND`); values travel via `env:`.
 */
export interface WorkflowInput {
  slug: string;
  postAs: CiPostAs;
  triggers: CiTrigger[];
}

/** The runner step's command: identical for every agent / repo / skill set (AC-25). */
export const RUN_COMMAND = `node ${RUNNER_ENTRY}`;

const SLUG_RE = /^[a-z0-9-]{1,64}$/;
const POST_AS: readonly CiPostAs[] = ['github_review', 'pr_comment', 'none'];

export function buildWorkflow(input: WorkflowInput): string {
  if (!SLUG_RE.test(input.slug)) throw new Error('invalid agent slug');
  if (!POST_AS.includes(input.postAs)) throw new Error('invalid post_as');
  const triggers = TRIGGER_ORDER.filter((t) => input.triggers.includes(t));
  if (triggers.length === 0 || triggers.length !== new Set(input.triggers).size) {
    throw new Error('invalid triggers');
  }
  const canPublish = input.postAs !== 'none';

  const lines = [
    '# Generated by DevDigest. Re-exporting from the studio regenerates this file.',
    'name: DevDigest Review',
    '',
    'on:',
    '  pull_request:',
    `    types: [${triggers.join(', ')}]`,
    '',
    'permissions:',
    '  contents: read',
    ...(canPublish ? ['  pull-requests: write'] : []),
    '',
    'jobs:',
    '  review:',
    '    # Fork PRs never receive secrets; skip them rather than fail.',
    '    if: github.event.pull_request.head.repo.full_name == github.repository',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 15',
    '    steps:',
    `      - uses: ${ACTION_CHECKOUT} # v4.4.0`,
    '        with:',
    '          persist-credentials: false',
    `      - uses: ${ACTION_SETUP_NODE} # v4.4.0`,
    '        with:',
    `          node-version: ${NODE_VERSION}`,
    '      - name: Run DevDigest review',
    `        run: ${RUN_COMMAND}`,
    '        env:',
    `          ${OPENROUTER_SECRET}: \${{ secrets.${OPENROUTER_SECRET} }}`,
    `          ${GITHUB_TOKEN_SECRET}: \${{ secrets.${GITHUB_TOKEN_SECRET} }}`,
    '          GITHUB_REPOSITORY: ${{ github.repository }}',
    '          DEVDIGEST_PR_NUMBER: ${{ github.event.pull_request.number }}',
    '          DEVDIGEST_HEAD_SHA: ${{ github.event.pull_request.head.sha }}',
    '          DEVDIGEST_WORKFLOW_RUN_ID: ${{ github.run_id }}',
    `          DEVDIGEST_AGENT: "${input.slug}"`,
    `          DEVDIGEST_POST_AS: ${input.postAs}`,
    '      - name: Upload result',
    '        if: always()',
    `        uses: ${ACTION_UPLOAD_ARTIFACT} # v4.6.2`,
    '        with:',
    `          name: ${ARTIFACT_NAME}`,
    `          path: ${ARTIFACT_FILE}`,
    '          if-no-files-found: ignore',
    '',
  ];
  return lines.join('\n');
}
